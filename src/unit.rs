

#[allow(non_upper_case_globals)]
pub const KiB: u64 = 1024;

#[allow(non_upper_case_globals)]
pub const MiB: u64 = 1024 * KiB;

#[allow(non_upper_case_globals)]
pub const GiB: u64 = 1024 * MiB;


#[allow(non_upper_case_globals)]
pub const Min: u32 = 60;

#[allow(non_upper_case_globals)]
pub const Hr: u32 = 60 * Min;

#[allow(non_upper_case_globals)]
pub const Day: u32 = 24 * Hr;
